// Regenerate src/actions_js.h from wasmcart's src/actions.js, so the native hosts run
// the same input-actions host code as CartHost / CartHostWeb.
//   node scripts/gen-actions-js.mjs <wasmcart checkout>/src/actions.js
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';

const src = process.argv[2];
if (!src) { console.error('usage: gen-actions-js.mjs <wasmcart>/src/actions.js'); process.exit(2); }
const body = readFileSync(src, 'utf8').replace(/^export /gm, '');
if (body.includes(')WCJS')) throw new Error('actions.js contains the raw-string delimiter');
const out = `// GENERATED by scripts/gen-actions-js.mjs from wasmcart's src/actions.js. Do not edit.
//
// WC_ACTIONS_LIB_JS evaluates to the exports of actions.js: the host side of
// input actions (wasmcart SPEC.md, "Input actions"), shared verbatim with the
// JS hosts.
#ifndef WC_ACTIONS_JS_H
#define WC_ACTIONS_JS_H
static const char WC_ACTIONS_LIB_JS[] = R"WCJS((function () {
'use strict';
${body}
return { ActionTable, DEVICE, GLYPH, IN, glyphId, padOrigin, padFamily, WORKER_ACTION_IMPORTS };
})())WCJS";
#endif
`;
const dest = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'actions_js.h');
writeFileSync(dest, out);
console.log(`wrote ${dest} (${out.length} bytes)`);
